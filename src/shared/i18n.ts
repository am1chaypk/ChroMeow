let current: 'en' | 'he' = 'en';

export function resolveLanguage(pref: Language): 'en' | 'he' {
  if (pref === 'en' || pref === 'he') return pref;
  const nav = typeof navigator !== 'undefined' ? navigator.language || '' : '';
  return nav.toLowerCase().startsWith('he') || nav.toLowerCase().startsWith('iw') ? 'he' : 'en';
}

export function setLanguage(pref: Language): 'en' | 'he' {
  current = resolveLanguage(pref);
  if (typeof document !== 'undefined') {
    document.documentElement.lang = current;
    document.documentElement.dir = current === 'he' ? 'rtl' : 'ltr';
  }
  return current;
}

/** Selects the UI language without touching the host document (content scripts). */
export function useLanguage(pref: Language): 'en' | 'he' {
  current = resolveLanguage(pref);
  return current;
}

export function lang(): 'en' | 'he' {
  return current;
}

export function t(key: string): string {
  const dict = current === 'he' ? HE : EN;
  return dict[key] ?? EN[key] ?? key;
}

/** Translates a key and fills `{name}` placeholders. */
export function tf(key: string, vars: Record<string, string | number>): string {
  return t(key).replace(/\{(\w+)\}/g, (m, k: string) => (k in vars ? String(vars[k]) : m));
}

export function stateLabel(state: CatState): string {
  return (current === 'he' ? STATE_LABELS_HE : STATE_LABELS_EN)[state] ?? state;
}

/** Built-in cats have a Hebrew name too; a name the user typed is always shown as typed. */
const BUILTIN_NAMES: Record<string, [string, string]> = {
  alex: ['Alex', 'אלכס'],
  anna: ['Anna', 'אנה'],
};

export function displayName(profile: { name: string; presetKey: string }): string {
  const pair = BUILTIN_NAMES[profile.presetKey];
  if (pair && (profile.name === pair[0] || profile.name === pair[1])) return pair[current === 'he' ? 1 : 0];
  return profile.name;
}

export function patternLabel(pattern: string): string {
  const pair = PATTERN_LABELS[pattern];
  return pair ? pair[current === 'he' ? 1 : 0] : pattern;
}

/** Applies translations to every element with data-i18n / data-i18n-title / data-i18n-placeholder. */
export function translateDom(root: ParentNode = document): void {
  root.querySelectorAll<HTMLElement>('[data-i18n]').forEach((el) => {
    el.textContent = t(el.dataset.i18n as string);
  });
  root.querySelectorAll<HTMLElement>('[data-i18n-title]').forEach((el) => {
    el.title = t(el.dataset.i18nTitle as string);
  });
  root.querySelectorAll<HTMLInputElement>('[data-i18n-placeholder]').forEach((el) => {
    el.placeholder = t(el.dataset.i18nPlaceholder as string);
  });
}
